export type I18nKey = keyof typeof en;

/** English only — this app has one interface language, forced in
    detectLocale(). `locale` stays a parameter on t()/tp() and every caller
    (rather than being deleted outright) so this can't silently drift out of
    sync with call sites if that ever changes. */
export function t(_locale: InterfaceLocale, key: I18nKey): string {
  return en[key] ?? key;
}

/** Translate a template with {placeholders}. */
export function tp(locale: InterfaceLocale, key: I18nKey, vars: Record<string, string | number>): string {
  return t(locale, key).replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars[name];
    if (value === undefined && import.meta.env?.DEV === true) {
      console.warn(`[i18n] missing placeholder {${name}} for key "${key}" (${locale})`);
    }
    return String(value ?? "");
  });
}

