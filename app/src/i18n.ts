/** Display name for a device connection type; unknown values pass through. */
const CONNECTIONS: Readonly<Record<string, I18nKey>> = {
  Wired: "conn.wired",
  Wireless: "conn.wireless",
};

export function connectionText(
  locale: InterfaceLocale,
  connection: string | null | undefined,
  fallback: I18nKey = "conn.wireless",
): string {
  if (!connection) return t(locale, fallback);
  const key = CONNECTIONS[connection];
  return key ? t(locale, key) : connection;
}

/** Localize a "Layer N" label produced by the protocol library without
    reimplementing its display-index mapping. */
export function layerLabel(locale: InterfaceLocale, libLabel: string): string {
  const match = /^Layer (.*)$/.exec(libLabel);
  return match ? tp(locale, "key.layerName", { n: match[1] }) : libLabel;
}
